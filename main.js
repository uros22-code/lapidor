function updateFinishDisplay(finishKey, lang = currentLang) {
  const tagEl = document.getElementById('finish-tag');
  const titleEl = document.getElementById('finish-title');
  const descEl = document.getElementById('finish-description');
  const appsEl = document.getElementById('finish-apps');

  const langData = finishesData[lang] || finishesData.sl;
  const data = langData[finishKey];

  if (data) {
    if (tagEl) tagEl.textContent = data.tag;
    if (titleEl) titleEl.textContent = data.title;
    if (descEl) descEl.textContent = data.desc;

    if (appsEl && data.apps) {
      appsEl.innerHTML = data.apps.map(app => 
        `<li><i class="fa-solid fa-check text-gold"></i> ${app}</li>`
      ).join('');
    }
  }
}

function initFinishesExplorer() {
  const tabs = document.querySelectorAll('.finish-tab');

  tabs.forEach(tab => {
    tab.addEventListener('click', () => {
      tabs.forEach(t => t.classList.remove('active'));
      tab.classList.add('active');

      const finishKey = tab.getAttribute('data-finish');
      updateFinishDisplay(finishKey, currentLang);
    });
  });
}

