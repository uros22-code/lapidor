/* --------------------------------------------------
 * Language Switcher Engine
 * -------------------------------------------------- */
function initLanguageSwitcher() {
  setLanguage(currentLang);

  document.querySelectorAll('[data-lang-btn]').forEach(btn => {
    btn.addEventListener('click', (e) => {
      e.preventDefault();
      const lang = btn.getAttribute('data-lang-btn');
      setLanguage(lang);
    });
  });
}

function setLanguage(lang) {
  currentLang = lang;
  localStorage.setItem('lapidor_language', lang);
  document.documentElement.lang = lang;

  document.querySelectorAll('[data-lang-btn]').forEach(btn => {
    if (btn.getAttribute('data-lang-btn') === lang) {
      btn.classList.add('active');
    } else {
      btn.classList.remove('active');
    }
  });

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (i18n[lang] && i18n[lang][key] !== undefined) {
      el.innerHTML = i18n[lang][key];
    }
  });

  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (i18n[lang] && i18n[lang][key] !== undefined) {
      el.setAttribute('placeholder', i18n[lang][key]);
    }
  });

  document.querySelectorAll('.lang-content').forEach(el => {
    if (el.classList.contains(`lang-${lang}`)) {
      el.style.display = 'block';
    } else {
      el.style.display = 'none';
    }
  });

  const activeTab = document.querySelector('.finish-tab.active');
  if (activeTab) {
    const finishKey = activeTab.getAttribute('data-finish');
    updateFinishDisplay(finishKey, lang);
  }
}

/* --------------------------------------------------
 * 0. Replace 'I' in LAPIDOR with Logo Pillar Symbol
 * -------------------------------------------------- */
function initPillarISymbol() {
  const pillarSvg = `<svg class="pillar-i-svg" viewBox="0 0 16 32"><rect x="1" y="2" width="14" height="3" rx="0.5"/><rect x="3" y="6" width="2.5" height="20" rx="0.5"/><rect x="6.75" y="6" width="2.5" height="20" rx="0.5"/><rect x="10.5" y="6" width="2.5" height="20" rx="0.5"/><rect x="1" y="27" width="14" height="3" rx="0.5"/></svg>`;
  const replacementHtml = `LAP${pillarSvg}DOR`;

  function replaceInNode(node) {
    if (node.nodeType === Node.TEXT_NODE) {
      if (node.nodeValue.includes('LAPIDOR')) {
        const span = document.createElement('span');
        span.innerHTML = node.nodeValue.replace(/LAPIDOR/g, replacementHtml);
        node.parentNode.replaceChild(span, node);
      }
    } else if (node.nodeType === Node.ELEMENT_NODE && !['SCRIPT', 'STYLE', 'TEXTAREA', 'INPUT', 'IMG', 'SVG'].includes(node.tagName)) {
      Array.from(node.childNodes).forEach(replaceInNode);
    }
  }

  replaceInNode(document.body);
}

/* --------------------------------------------------
 * 1. Navigation & Mobile Menu
 * -------------------------------------------------- */
function initNavigation() {
  const header = document.getElementById('header');
  const mobileToggle = document.getElementById('mobile-toggle');
  const mainNav = document.getElementById('main-nav');
  const navLinks = document.querySelectorAll('.nav-link');

  navLinks.forEach(link => {
    link.addEventListener('click', () => {
      navLinks.forEach(l => l.classList.remove('active'));
      link.classList.add('active');

      if (mainNav) {
        mainNav.classList.remove('active');
        const icon = mobileToggle?.querySelector('i');
        if (icon) {
          icon.classList.remove('fa-xmark');
          icon.classList.add('fa-bars');
        }
      }
    });
  });

  const sections = document.querySelectorAll('section[id], footer[id]');
  window.addEventListener('scroll', () => {
    if (window.scrollY > 50) {
      header.style.background = 'rgba(250, 248, 245, 0.96)';
      header.style.boxShadow = '0 8px 25px rgba(0, 0, 0, 0.06)';
    } else {
      header.style.background = 'rgba(250, 248, 245, 0.94)';
      header.style.boxShadow = 'none';
    }

    let currentSectionId = '';
    const scrollPosition = window.scrollY + 180;

    sections.forEach(section => {
      const sectionTop = section.offsetTop;
      const sectionHeight = section.offsetHeight;
      if (scrollPosition >= sectionTop && scrollPosition < sectionTop + sectionHeight) {
        currentSectionId = section.getAttribute('id');
      }
    });

    if (currentSectionId) {
      navLinks.forEach(link => {
        link.classList.remove('active');
        if (link.getAttribute('href') === `#${currentSectionId}`) {
          link.classList.add('active');
        }
      });
    }
  });

  if (mobileToggle && mainNav) {
    const toggleMenu = (show) => {
      const icon = mobileToggle.querySelector('i');
      const isShow = show === undefined ? !mainNav.classList.contains('active') : show;
      
      if (isShow) {
        mainNav.classList.add('active');
        if (icon) {
          icon.classList.remove('fa-bars');
          icon.classList.add('fa-xmark');
        }
      } else {
        mainNav.classList.remove('active');
        if (icon) {
          icon.classList.remove('fa-xmark');
          icon.classList.add('fa-bars');
        }
      }
    };

    mobileToggle.addEventListener('click', (e) => {
      e.stopPropagation();
      toggleMenu();
    });

    navLinks.forEach(link => {
      link.addEventListener('click', () => {
        toggleMenu(false);
      });
    });

    document.addEventListener('click', (e) => {
      if (mainNav.classList.contains('active') && !mainNav.contains(e.target) && !mobileToggle.contains(e.target)) {
        toggleMenu(false);
      }
    });
  }
}

/* --------------------------------------------------
 * 2. Product Catalog Filter
 * -------------------------------------------------- */
function initProductCatalog() {
  const filterBtns = document.querySelectorAll('.filter-btn');
  const productCards = document.querySelectorAll('.product-card');

  filterBtns.forEach(btn => {
    btn.addEventListener('click', () => {
      filterBtns.forEach(b => b.classList.remove('active'));
      btn.classList.add('active');

      const filterValue = btn.getAttribute('data-filter');

      productCards.forEach(card => {
        const category = card.getAttribute('data-category');
        if (filterValue === 'all' || category === filterValue) {
          card.style.display = 'block';
          card.style.animation = 'fadeIn 0.5s ease forwards';
        } else {
          card.style.display = 'none';
        }
      });
    });
  });
}

